// Classification

function classify(toks, kind) {
  const code = toks.filter((t) => t.type !== "comment");
  const encl = new Array(code.length).fill(-1);
  const match = new Array(code.length).fill(-1);
  const stack = [];
  for (let i = 0; i < code.length; i += 1) {
    const t = code[i];
    t.role = null;
    t.k = null;
    t.v = undefined;
    t.cls = undefined;
    t.unary = false;
    t.body = false;
    t.forceBreak = false;
    encl[i] = stack.length ? stack[stack.length - 1] : -1;
    if (t.type === "punct" && (t.value === "(" || t.value === "[")) stack.push(i);
    else if (t.type === "punct" && (t.value === ")" || t.value === "]") && stack.length) match[stack.pop()] = i;
  }
  const ctx = { code, encl, match, kind };
  markDefs(ctx);
  markPhrases(code);
  for (let i = 0; i < code.length; i += 1) {
    const t = code[i];
    if (t.type === "word") classifyWord(ctx, i);
    else if (t.type === "number") t.cls = "n";
    else if (t.type === "param" || t.type === "tpl") t.cls = "param";
    else if (t.type === "punct") t.cls = "p";
    else if (t.type === "op") {
      t.cls = "p";
      if (t.value === "-" || t.value === "+" || t.value === "~") {
        const prev = code[i - 1];
        t.unary =
          !prev ||
          prev.type === "op" ||
          (prev.type === "punct" && prev.value !== ")" && prev.value !== "]") ||
          (prev.type === "word" && prev.k === "kw" && !VALUE_END_KW.has(prev.upper));
      }
    }
  }
  markBodies(ctx);
}

function setKind(t, k) {
  t.k = k;
  if (k === "kw") {
    t.v = t.upper;
    t.cls = t.upper === "TRUE" || t.upper === "FALSE" ? "b" : t.upper === "NULL" ? "u" : "kw";
  } else if (k === "fn") {
    t.v = FUNCTIONS.has(t.upper) ? t.upper : t.value;
    t.cls = "fn";
  } else if (k === "type") {
    t.v = TYPES.has(t.upper) || AMBIG_TYPES.has(t.upper) || TYPE_CONT.has(t.upper) ? t.upper : t.value;
    t.cls = "ty";
  } else {
    t.v = t.value;
    t.cls = undefined;
  }
}

function isP(t, v) {
  return t && t.type === "punct" && t.value === v;
}

function isW(t, up) {
  return t && t.type === "word" && (up == null || t.upper === up);
}

function markPhrases(code) {
  for (let i = 0; i < code.length; i += 1) {
    if (!isW(code[i]) || code[i].role || isP(code[i - 1], ".")) continue;
    for (const ph of PHRASES) {
      let ok = true;
      for (let k = 0; k < ph.length; k += 1) {
        const t = code[i + k];
        if (!isW(t, ph[k]) || t.role || isP(code[i + k + 1], ".") || isP(code[i + k + 1], "(")) {
          ok = false;
          break;
        }
      }
      if (!ok) continue;
      for (let k = 0; k < ph.length; k += 1) code[i + k].role = "kw";
      i += ph.length - 1;
      break;
    }
  }
}

function markDefs(ctx) {
  const { code, match, kind } = ctx;
  const ups = code.map((t) => (t.type === "word" ? t.upper : ""));
  const first = ups[0];
  if (kind === "declare") {
    markDefItems(ctx, 1, code.length, true);
    return;
  }
  if (kind === "decl") {
    markDefItem(ctx, 0, code.length);
    return;
  }
  if (first === "CREATE") {
    const tableAt = ups.indexOf("TABLE");
    const fnAt = ups.findIndex((u) => u === "FUNCTION" || u === "PROCEDURE");
    const asAt = ups.indexOf("AS");
    if (tableAt > 0 && (fnAt < 0 || tableAt < fnAt)) {
      const open = code.findIndex((t, k) => k > tableAt && isP(t, "("));
      if (open > 0 && (asAt < 0 || open < asAt) && match[open] > 0) {
        code[open].forceBreak = true;
        markDefItems(ctx, open + 1, match[open], false);
      }
    } else if (fnAt > 0) {
      const open = code.findIndex((t, k) => k > fnAt && isP(t, "("));
      if (open > 0 && match[open] > 0) markDefItems(ctx, open + 1, match[open], false);
      const ret = ups.indexOf("RETURNS");
      if (ret > 0) {
        if (ups[ret + 1] === "TABLE" && isP(code[ret + 2], "(") && match[ret + 2] > 0) {
          markDefItems(ctx, ret + 3, match[ret + 2], false);
        } else if (ups[ret + 1] === "SETOF") markType(code, ret + 2);
        else markType(code, ret + 1);
      }
    }
  }
  if (first === "ALTER") {
    for (let i = 1; i < code.length; i += 1) {
      if (ups[i] === "ADD" && encl(ctx, i) < 0) {
        let j = i + 1;
        if (ups[j] === "COLUMN") j += 1;
        else if (CONSTRAINT_STARTS.has(ups[j]) || ups[j] === "PARTITION") continue;
        if (ups[j] === "IF" && ups[j + 1] === "NOT" && ups[j + 2] === "EXISTS") j += 3;
        markDefItem(ctx, j, code.length);
      }
      if (ups[i] === "TYPE" && (ups[i - 1] === "DATA" || code[i - 1]?.type === "word" || code[i - 1]?.type === "qname")) {
        if (ups[i - 2] === "ALTER" || ups[i - 2] === "COLUMN" || ups[i - 1] === "DATA") markType(code, i + 1);
      }
    }
  }
}

function encl(ctx, i) {
  return ctx.encl[i];
}

function markType(code, j) {
  const t = code[j];
  if (!t || t.type !== "word" && t.type !== "qname") return j;
  t.role = "type";
  j += 1;
  while (code[j] && isW(code[j]) && TYPE_CONT.has(code[j].upper)) {
    code[j].role = "type";
    j += 1;
  }
  return j;
}

function markDefItems(ctx, from, to, declare) {
  const { code, encl: en } = ctx;
  const base = en[from] ?? -1;
  let start = from;
  for (let i = from; i <= to; i += 1) {
    if (i === to || (isP(code[i], ",") && en[i] === base)) {
      markDefItem(ctx, start, i, declare);
      start = i + 1;
    }
  }
}

function markDefItem(ctx, from, to) {
  const { code } = ctx;
  let j = from;
  while (j < to && isW(code[j]) && ["IN", "OUT", "INOUT", "VARIADIC"].includes(code[j].upper)) {
    code[j].role = "kw";
    j += 1;
  }
  const first = code[j];
  if (!first || j >= to) return;
  if (isW(first) && CONSTRAINT_STARTS.has(first.upper)) return;
  const after = code[j + 1];
  if (isW(first) && (TYPES.has(first.upper) || AMBIG_TYPES.has(first.upper)) && (j + 1 >= to || isP(after, "(") || isP(after, "["))) {
    markType(code, j);
    return;
  }
  if (first.type !== "word" && first.type !== "qname" && first.type !== "param") return;
  if (first.type === "word") first.role = "ident";
  if (j + 1 < to && isW(code[j + 1]) && code[j + 1].upper === "CONSTANT") {
    code[j + 1].role = "kw";
    j += 1;
  }
  if (j + 1 < to && isW(code[j + 1], "AS")) j += 1;
  if (j + 1 < to) markType(code, j + 1);
}

function markBodies(ctx) {
  const { code } = ctx;
  let lang = "";
  for (let i = 0; i < code.length - 1; i += 1) {
    if (isW(code[i], "LANGUAGE") && code[i].k === "kw") {
      const n = code[i + 1];
      lang = String(n.type === "string" ? n.value : n.value).toLowerCase().replace(/["'`]/g, "");
    }
  }
  for (let i = 1; i < code.length; i += 1) {
    const t = code[i];
    const prev = code[i - 1];
    if (t.type === "string" && t.dollar && isW(prev) && (prev.upper === "AS" || prev.upper === "DO")) {
      t.body = true;
      t.lang = lang || "plpgsql";
    }
  }
}

function classifyWord(ctx, i) {
  const { code, kind } = ctx;
  const t = code[i];
  const up = t.upper;
  const prev = code[i - 1];
  const next = code[i + 1];
  if (t.role) return setKind(t, t.role);
  if (isP(prev, ".") && !isP(next, "(")) return setKind(t, "ident");
  if (isP(next, ".")) return setKind(t, "ident");
  if (prev && prev.type === "op" && prev.value === "::") return setKind(t, "type");
  if (i === 0 && (up === "IF" || up === "WHILE")) return setKind(t, "kw");

  if (DATE_UNITS.has(up) && isUnit(ctx, i)) return setKind(t, "kw");

  if (isP(next, "(")) {
    if (KW_BEFORE_PAREN.has(up)) return setKind(t, "kw");
    if (TYPES.has(up) && !FUNCTIONS.has(up)) return setKind(t, "type");
    if (AMBIG_TYPES.has(up) && !FUNCTIONS.has(up) && typeContext(ctx, i)) return setKind(t, "type");
    if (FUNCTIONS.has(up)) return setKind(t, "fn");
    let head = i;
    while (head > 1 && isP(code[head - 1], ".")) head -= 2;
    const before = code[head - 1];
    if (isW(before) && TABLE_BEFORE_PAREN.has(before.upper) && before.k === "kw") return setKind(t, "ident");
    if (kind === "ddl" && isW(before, "USING")) return setKind(t, "ident");
    if (head !== i) return setKind(t, "fn");
    const close = ctx.match[i + 1];
    if (close > 0 && isW(code[close + 1], "AS")) return setKind(t, "ident");
    return setKind(t, "fn");
  }

  if (isW(prev, "AS") && prev.k === "kw") {
    if (AS_FOLLOW.has(up)) return setKind(t, "kw");
    if (inCast(ctx, i) || TYPES.has(up)) return setKind(t, "type");
    return setKind(t, "ident");
  }

  if (RESERVED.has(up)) return setKind(t, "kw");
  if ((up === "TOP" && isW(prev) && ["SELECT", "DISTINCT", "ALL", "DELETE", "UPDATE"].includes(prev.upper)) ||
      (up === "PERCENT" && isW(code[i - 2], "TOP"))) {
    return setKind(t, "kw");
  }
  if (kind === "ddl" && DDL_SOFT.has(up) && !identPosition(code, i)) return setKind(t, "kw");
  if (TYPES.has(up)) return setKind(t, "type");
  if (AMBIG_TYPES.has(up) && typeContext(ctx, i)) return setKind(t, "type");
  if (TYPE_CONT.has(up) && prev && prev.k === "type") return setKind(t, "type");
  return setKind(t, "ident");
}

function identPosition(code, i) {
  const prev = code[i - 1];
  if (!prev) return false;
  if (isP(prev, ",") || isP(prev, "(")) return true;
  return isW(prev) && (IDENT_AFTER.has(prev.upper) || prev.upper === "EXISTS") && prev.k === "kw";
}

function inCast(ctx, i) {
  const open = ctx.encl[i];
  if (open < 1) return false;
  const fn = ctx.code[open - 1];
  return isW(fn) && ["CAST", "TRY_CAST", "SAFE_CAST", "CONVERT", "TRY_CONVERT"].includes(fn.upper);
}

function typeContext(ctx, i) {
  const { code } = ctx;
  const prev = code[i - 1];
  const next = code[i + 1];
  if (isW(prev) && (prev.upper === "RETURNS" || prev.upper === "TYPE")) return true;
  if (next && next.type === "string" && !next.prefix && ["DATE", "TIME", "TIMESTAMP", "INTERVAL", "JSON"].includes(code[i].upper)) return true;
  return false;
}

function isUnit(ctx, i) {
  const { code } = ctx;
  const prev = code[i - 1];
  const next = code[i + 1];
  if (prev && (prev.type === "number" || prev.type === "string") && isW(code[i - 2], "INTERVAL")) return true;
  if (isW(prev, "TO") && isW(code[i - 3], "INTERVAL")) return true;
  const open = ctx.encl[i];
  if (open < 1) return false;
  const fn = code[open - 1];
  if (!isW(fn) || !UNIT_FNS.has(fn.upper)) return false;
  if (fn.upper === "EXTRACT") return isW(next, "FROM");
  const startArg = isP(prev, "(") || isP(prev, ",");
  const endArg = isP(next, ")") || isP(next, ",");
  return startArg && endArg;
}

