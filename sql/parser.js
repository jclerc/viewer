export function viewSql(text) {
  const src = String(text ?? "").replace(/^﻿/, "");
  const lexer = new Lexer(src);
  const tokens = lexer.run();
  const stmts = splitStatements(tokens);
  const statements = stmts.filter((s) => !s.special && s.tokens.some((t) => t.type !== "comment")).length;
  let nodes;
  let truncated = lexer.truncated;
  try {
    const out = formatScript(stmts);
    nodes = out.nodes;
    truncated = truncated || out.truncated;
  } catch {
    nodes = verbatimNodes(src, tokens, stmts);
  }
  return { nodes, formatted: nodesToFormatted(nodes), truncated, statements };
}

export function formatSql(text) {
  return viewSql(text).formatted;
}

export function tokenizeSql(text) {
  const tokens = new Lexer(String(text ?? "")).run();
  for (const st of splitStatements(tokens)) {
    if (!st.special) classify(st.tokens, statementKind(st.tokens));
  }
  return tokens;
}

export function splitSql(text) {
  return splitStatements(new Lexer(String(text ?? "")).run())
    .filter((s) => !s.special && s.tokens.some((t) => t.type !== "comment"))
    .map((s) => s.tokens.map((t) => t.raw).join(" "));
}

