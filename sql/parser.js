// Lexer

const isWordStart = (c) => /[A-Za-z_À-￿]/.test(c);
const isWordCont = (c) => /[A-Za-z0-9_$À-￿]/.test(c);
const isDigit = (c) => c >= "0" && c <= "9";

class Lexer {
  constructor(text) {
    this.s = text;
    this.n = text.length;
    this.i = 0;
    this.tokens = [];
    this.truncated = false;
    this.delim = ";";
    this.nl = 0;
    this.bol = true;
    this.lineStart = 0;
    this.stmt = [];
  }

  run() {
    while (this.i < this.n) this.step();
    return this.tokens;
  }

  push(tok, start, end) {
    tok.start = start;
    tok.end = end;
    tok.raw = this.s.slice(start, end);
    tok.nl = this.nl;
    tok.col = start - this.lineStart;
    this.nl = 0;
    this.bol = false;
    this.i = end;
    this.tokens.push(tok);
    if (tok.type === "word") this.stmt.push(tok.upper);
    return tok;
  }

  endStatement() {
    const w = this.stmt;
    this.stmt = [];
    if (w[0] !== "COPY") return;
    const k = w.indexOf("STDIN");
    if (k > 0 && w[k - 1] === "FROM") this.readCopyData();
  }

  readCopyData() {
    let j = this.i;
    while (j < this.n && this.s[j] !== "\n") {
      if (!/\s/.test(this.s[j])) return;
      j += 1;
    }
    if (j >= this.n) return;
    const start = j + 1;
    let k = start;
    let end = this.n;
    let next = this.n;
    while (k < this.n) {
      let e = this.s.indexOf("\n", k);
      if (e < 0) e = this.n;
      if (this.s.slice(k, e).replace(/\r$/, "") === "\\.") {
        end = k;
        next = e;
        break;
      }
      k = e + 1;
    }
    this.nl += 1;
    this.lineStart = start;
    const value = this.s.slice(start, end).replace(/\r?\n$/, "");
    this.push({ type: "copydata", value, ended: next < this.n || end < this.n }, start, next);
  }

  step() {
    const s = this.s;
    const i = this.i;
    const c = s[i];
    if (c === "\n") {
      this.nl += 1;
      this.i += 1;
      this.bol = true;
      this.lineStart = this.i;
      return;
    }
    if (c === " " || c === "\t" || c === "\r" || c === "\f" || c === "\v" || c === " ") {
      this.i += 1;
      return;
    }
    if (this.bol && this.lineMeta()) return;

    if (this.delim !== ";" && s.startsWith(this.delim, i)) {
      this.push({ type: "delim", value: this.delim }, i, i + this.delim.length);
      this.endStatement();
      return;
    }

    const c2 = s[i + 1];
    if (c === "-" && c2 === "-") return this.lineComment(i);
    if (c === "#") {
      if (c2 === ">" || c2 === "-") return this.op(i);
      if (!this.bol && c2 && (isWordStart(c2) || c2 === "#")) return this.word(i, i + 1);
      return this.lineComment(i);
    }
    if (c === "/" && c2 === "*") return this.blockComment(i);
    if (c === "{" && (c2 === "{" || c2 === "%" || c2 === "#")) return this.template(i);
    if (c === "'") return this.quoted(i, i, "'", "");
    if (c === '"') return this.ident(i, '"', '"');
    if (c === "`") return this.ident(i, "`", "`");
    if (c === "[" && this.bracketIdent(i)) return this.ident(i, "[", "]");
    if (c === "$") return this.dollar(i);
    if (isDigit(c) || (c === "." && isDigit(c2) && !this.afterAtom())) return this.number(i);
    if (c === "?") {
      if (c2 === "|" || c2 === "&") return this.op(i);
      let j = i + 1;
      while (j < this.n && isDigit(s[j])) j += 1;
      this.push({ type: "param", value: s.slice(i, j) }, i, j);
      return;
    }
    if (c === ":" && c2 && isWordStart(c2) && s[i - 1] !== ":") {
      let j = i + 2;
      while (j < this.n && isWordCont(s[j])) j += 1;
      this.push({ type: "param", value: s.slice(i, j) }, i, j);
      return;
    }
    if (c === "@" && c2 && (isWordStart(c2) || c2 === "@")) {
      let j = i + 1;
      while (s[j] === "@") j += 1;
      while (j < this.n && isWordCont(s[j])) j += 1;
      this.push({ type: "param", value: s.slice(i, j) }, i, j);
      return;
    }
    if (c === "%") {
      const m = /^%(\([^)\s]*\))?[sdf](?![A-Za-z0-9_])/.exec(s.slice(i, i + 64));
      if (m) {
        this.push({ type: "param", value: m[0] }, i, i + m[0].length);
        return;
      }
    }
    if ("(),;.[]{}".includes(c)) {
      const tok = this.push({ type: "punct", value: c }, i, i + 1);
      if (c === ";" && this.delim === ";") {
        tok.term = true;
        this.endStatement();
      }
      return;
    }
    if (isWordStart(c)) return this.word(i, i);
    this.op(i);
  }

  lineMeta() {
    const s = this.s;
    let eol = s.indexOf("\n", this.i);
    if (eol < 0) eol = this.n;
    const line = s.slice(this.i, eol).replace(/\r$/, "");
    const d = /^delimiter\s+(\S+)\s*$/i.exec(line);
    if (d) {
      this.push({ type: "meta", value: line.trim(), delim: d[1] }, this.i, eol);
      this.delim = d[1];
      this.stmt = [];
      return true;
    }
    if (line[0] === "\\") {
      this.push({ type: "meta", value: line.trimEnd() }, this.i, eol);
      return true;
    }
    if (/^go(\s+\d+)?\s*(--.*)?$/i.test(line)) {
      this.push({ type: "go", value: line.trim() }, this.i, eol);
      this.stmt = [];
      return true;
    }
    return false;
  }

  lineComment(i) {
    let j = this.s.indexOf("\n", i);
    if (j < 0) j = this.n;
    const value = this.s.slice(i, j).replace(/\r$/, "").trimEnd();
    this.push({ type: "comment", value, line: true }, i, i + value.length || j);
  }

  blockComment(i) {
    const s = this.s;
    let depth = 1;
    let j = i + 2;
    while (j < this.n && depth) {
      if (s[j] === "/" && s[j + 1] === "*") {
        depth += 1;
        j += 2;
      } else if (s[j] === "*" && s[j + 1] === "/") {
        depth -= 1;
        j += 2;
      } else j += 1;
    }
    if (depth) this.truncated = true;
    const tok = { type: "comment", value: s.slice(i, j), block: true, closed: !depth };
    this.push(tok, i, j);
  }

  template(i) {
    const s = this.s;
    const close = { "{": "}}", "%": "%}", "#": "#}" }[s[i + 1]];
    let j = s.indexOf(close, i + 2);
    j = j < 0 ? this.n : j + 2;
    const value = s.slice(i, j);
    if (s[i + 1] === "{") this.push({ type: "tpl", value }, i, j);
    else this.push({ type: "comment", value, block: true, tpl: true, closed: true }, i, j);
  }

  quoted(start, i, q, prefix) {
    const s = this.s;
    let j = i + 1;
    let closed = false;
    while (j < this.n) {
      const c = s[j];
      if (c === q) {
        if (s[j + 1] === q) {
          j += 2;
          continue;
        }
        closed = true;
        break;
      }
      if (c === "\\" && q === "'") {
        j += 2;
        continue;
      }
      j += 1;
    }
    if (!closed) this.truncated = true;
    const value = s.slice(i + 1, Math.min(j, this.n));
    this.push({ type: "string", value, quote: q, prefix, closed }, start, closed ? j + 1 : this.n);
  }

  ident(i, open, close) {
    const s = this.s;
    let j = i + 1;
    let closed = false;
    while (j < this.n) {
      if (s[j] === close) {
        if (s[j + 1] === close && open !== "[") {
          j += 2;
          continue;
        }
        closed = true;
        break;
      }
      j += 1;
    }
    if (!closed) this.truncated = true;
    const end = closed ? j + 1 : this.n;
    this.push({ type: "qname", value: s.slice(i, end), closed }, i, end);
  }

  bracketIdent(i) {
    const prev = this.lastCode();
    if (prev) {
      if (prev.type === "qname" || prev.type === "string" || prev.type === "number") return false;
      if (prev.type === "punct" && (prev.value === ")" || prev.value === "]")) return false;
      if (prev.type === "word" && (!RESERVED.has(prev.upper) || prev.upper === "ARRAY")) return false;
    }
    return /^\[[A-Za-z_@#À-￿][^\]\n]*\]/.test(this.s.slice(i, i + 256));
  }

  afterAtom() {
    const prev = this.lastCode();
    if (!prev || prev.end !== this.i) return false;
    return prev.type === "word" || prev.type === "qname" || (prev.type === "punct" && prev.value === ")");
  }

  lastCode() {
    for (let k = this.tokens.length - 1; k >= 0; k -= 1) {
      if (this.tokens[k].type !== "comment") return this.tokens[k];
    }
    return null;
  }

  dollar(i) {
    const s = this.s;
    const m = /^\$([A-Za-z_À-￿][A-Za-z0-9_À-￿]*)?\$/.exec(s.slice(i, i + 128));
    if (m) {
      const tag = m[0];
      const close = s.indexOf(tag, i + tag.length);
      const closed = close >= 0;
      if (!closed) this.truncated = true;
      const end = closed ? close + tag.length : this.n;
      const value = s.slice(i + tag.length, closed ? close : this.n);
      this.push({ type: "string", value, quote: tag, prefix: "", closed, dollar: true }, i, end);
      return;
    }
    let j = i + 1;
    while (j < this.n && isWordCont(s[j])) j += 1;
    if (j > i + 1) this.push({ type: "param", value: s.slice(i, j) }, i, j);
    else this.op(i);
  }

  number(i) {
    const s = this.s;
    let j = i;
    const hex = /^0[xX][0-9a-fA-F_]+/.exec(s.slice(i, i + 64)) || /^0[bB][01_]+/.exec(s.slice(i, i + 130));
    if (hex) j = i + hex[0].length;
    else {
      while (j < this.n && (isDigit(s[j]) || s[j] === "_")) j += 1;
      if (s[j] === "." && s[j + 1] !== ".") {
        j += 1;
        while (j < this.n && (isDigit(s[j]) || s[j] === "_")) j += 1;
      }
      if ((s[j] === "e" || s[j] === "E") && (isDigit(s[j + 1]) || ((s[j + 1] === "+" || s[j + 1] === "-") && isDigit(s[j + 2])))) {
        j += 2;
        while (j < this.n && isDigit(s[j])) j += 1;
      }
    }
    if (j < this.n && isWordStart(s[j]) && !/[eE]/.test(s[j])) {
      // 1st, 2a: not a number, treat as a word.
      while (j < this.n && isWordCont(s[j])) j += 1;
      const value = s.slice(i, j);
      this.push({ type: "word", value, upper: value.toUpperCase() }, i, j);
      return;
    }
    this.push({ type: "number", value: s.slice(i, j) }, i, j);
  }

  word(start, i) {
    const s = this.s;
    let j = i + 1;
    while (j < this.n && isWordCont(s[j]) && !(this.delim !== ";" && s.startsWith(this.delim, j))) j += 1;
    const value = s.slice(start, j);
    if (s[j] === "'" && /^(e|n|x|b|r|rb|br|u|_[a-z0-9]+)$/i.test(value)) {
      this.quoted(start, j, "'", value);
      return;
    }
    if (s[j] === "&" && s[j + 1] === "'" && /^u$/i.test(value)) {
      this.quoted(start, j + 1, "'", `${value}&`);
      return;
    }
    this.push({ type: "word", value, upper: value.toUpperCase() }, start, j);
  }

  op(i) {
    const s = this.s;
    for (const o of MULTI_OPS) {
      if (s.startsWith(o, i)) {
        this.push({ type: "op", value: o }, i, i + o.length);
        return;
      }
    }
    this.push({ type: "op", value: s[i] }, i, i + 1);
  }
}

// ---------------------------------------------------------------------------
// Statements

function isTerm(t) {
  return t && (t.type === "delim" || (t.type === "punct" && t.value === ";"));
}

function isBlockBegin(toks, i) {
  const n = nextCode(toks, i);
  if (!n || isTerm(n) || n.type === "go") return false;
  if (n.type === "word" && TXN_AFTER_BEGIN.has(n.upper)) return false;
  return true;
}

function nextCode(toks, i) {
  for (let j = i + 1; j < toks.length; j += 1) {
    if (toks[j].type !== "comment") return toks[j];
  }
  return null;
}

function nextCodeIndex(toks, i) {
  for (let j = i + 1; j < toks.length; j += 1) {
    if (toks[j].type !== "comment") return j;
  }
  return -1;
}

function splitStatements(tokens) {
  const out = [];
  let cur = [];
  let stack = [];
  let skipCase = -1;
  const flush = (term) => {
    if (cur.length || term) out.push({ tokens: cur, term, trail: [] });
    cur = [];
    stack = [];
  };
  for (let i = 0; i < tokens.length; i += 1) {
    const t = tokens[i];
    if (t.type === "meta" || t.type === "go" || t.type === "copydata") {
      flush(null);
      out.push({ special: t, tokens: [t], trail: [] });
      continue;
    }
    if (t.type === "delim" || (t.type === "punct" && t.value === ";" && t.term && !stack.includes("begin"))) {
      flush(t);
      continue;
    }
    if (t.type === "word") {
      if (t.upper === "BEGIN" && isBlockBegin(tokens, i)) stack.push("begin");
      else if (t.upper === "CASE") {
        if (skipCase === i) skipCase = -1;
        else stack.push("case");
      } else if (t.upper === "END" && stack.length) {
        const j = nextCodeIndex(tokens, i);
        const nx = j >= 0 && tokens[j].type === "word" && tokens[j].nl === 0 ? tokens[j].upper : "";
        if (!["IF", "LOOP", "WHILE", "REPEAT", "FOR"].includes(nx)) {
          stack.pop();
          if (nx === "CASE") skipCase = j;
        }
      }
    }
    cur.push(t);
  }
  flush(null);

  // A comment on the same line as `;` belongs to the statement it ends.
  for (let k = 1; k < out.length; k += 1) {
    const prev = out[k - 1];
    const st = out[k];
    if (prev.special || st.special || !prev.term) continue;
    while (st.tokens.length && st.tokens[0].type === "comment" && st.tokens[0].nl === 0) {
      prev.trail.push(st.tokens.shift());
    }
  }
  for (const st of out) st.nl = st.tokens[0]?.nl ?? st.term?.nl ?? 0;
  return out.filter((st) => st.special || st.tokens.length || st.trail.length || st.term?.type === "delim");
}

function statementKind(toks) {
  const code = toks.filter((t) => t.type !== "comment");
  const first = code[0];
  if (!first) return "dml";
  if (first.type === "punct" && first.value === "(") return "dml";
  if (first.type !== "word") return "other";
  const up = first.upper;
  if (DML_START.has(up)) return "dml";
  if (up === "REPLACE" && code[1]?.upper === "INTO") return "dml";
  if (up === "DECLARE") return "declare";
  if (["CREATE", "ALTER", "DROP", "COMMENT", "GRANT", "REVOKE", "TRUNCATE", "DO", "RENAME"].includes(up)) return "ddl";
  return "other";
}

