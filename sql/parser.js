// Verbatim (source layout, highlighted): fallback when formatting fails

function verbatimNodes(src, tokens, stmts) {
  if (!tokens) {
    tokens = new Lexer(src).run();
    stmts = splitStatements(tokens);
  }
  for (const st of stmts) {
    if (!st.special) {
      try {
        classify(st.tokens, statementKind(st.tokens));
      } catch {
        /* keep raw */
      }
    }
  }
  const segs = [];
  let pos = 0;
  for (const t of tokens) {
    if (t.start > pos) segs.push({ text: src.slice(pos, t.start) });
    segs.push({ text: t.raw, cls: verbatimCls(t) });
    pos = t.end;
  }
  if (pos < src.length) segs.push({ text: src.slice(pos) });
  const lines = [[]];
  for (const seg of segs) {
    const parts = seg.text.split(/\r?\n/);
    parts.forEach((part, k) => {
      if (k > 0) lines.push([]);
      if (part) lines[lines.length - 1].push({ type: "text", value: part.replace(/\r$/, ""), cls: seg.cls });
    });
  }
  while (lines.length > 1 && !lines[lines.length - 1].length) lines.pop();
  return lines.map((tokens) => ({ type: "line", tokens }));
}

function verbatimCls(t) {
  switch (t.type) {
    case "comment":
      return t.tpl ? "param" : "c";
    case "string":
      return "s";
    case "meta":
    case "go":
      return "kw";
    case "copydata":
    case "qname":
      return undefined;
    default:
      return t.cls;
  }
}
